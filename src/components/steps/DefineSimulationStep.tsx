import { useEffect, useRef, useState } from 'react'
import {
  DOMAIN_OPTIONS,
  INDUSTRY_OPTIONS,
  DURATION_OPTIONS,
  LEARNING_OBJECTIVES,
} from '../../data/mockData'
import { useSimulation } from '../../context/SimulationContext'
import { api, type AiStatus } from '../../api/client'
import type { ContentCreationMode, Difficulty, PlayMode } from '../../types/simulation'

const DIFFICULTIES: Difficulty[] = ['Beginner', 'Intermediate', 'Advanced']

export function DefineSimulationStep() {
  const { state, updateMeta, toggleObjective, runAIGeneration, runManualSetup, runDocumentGeneration, generating, generationError } =
    useSimulation()
  const { meta } = state
  const [aiStatus, setAiStatus] = useState<AiStatus | null>(null)
  const [documentFile, setDocumentFile] = useState<File | null>(null)
  const fileInputRef = useRef<HTMLInputElement>(null)

  useEffect(() => {
    api.getAiStatus().then(setAiStatus).catch(console.error)
  }, [])

  return (
    <div className="rounded-2xl border-2 border-violet-200 bg-white overflow-hidden shadow-sm">
      <div className="bg-violet-600 px-6 py-3 flex items-center gap-2">
        <span className="w-7 h-7 rounded-full bg-white/20 flex items-center justify-center text-white text-sm font-bold">
          1
        </span>
        <h2 className="text-white font-semibold">Define Simulation</h2>
      </div>

      <div className="p-6 space-y-5">
        {aiStatus && (
          <div
            className={`text-sm px-4 py-3 rounded-lg border ${
              aiStatus.configured
                ? 'bg-blue-50 border-blue-200 text-blue-800'
                : 'bg-amber-50 border-amber-200 text-amber-800'
            }`}
          >
            {aiStatus.configured ? (
              <>🤖 <strong>AI enabled</strong> — content will be generated by {aiStatus.model}</>
            ) : (
              <>⚙️ <strong>Demo mode</strong> — add <code className="text-xs bg-white/60 px-1 rounded">OPENAI_API_KEY</code> to <code className="text-xs bg-white/60 px-1 rounded">.env</code> for real LLM generation</>
            )}
          </div>
        )}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <label className="block">
            <span className="text-sm font-medium text-slate-700">Simulation Title</span>
            <input
              type="text"
              value={meta.title}
              onChange={(e) => updateMeta({ title: e.target.value })}
              className="mt-1 w-full px-3 py-2 border border-slate-300 rounded-lg text-sm focus:ring-2 focus:ring-violet-500 focus:border-violet-500 outline-none"
            />
          </label>

          <label className="block">
            <span className="text-sm font-medium text-slate-700">Domain / Category</span>
            <select
              value={meta.domain}
              onChange={(e) => updateMeta({ domain: e.target.value })}
              className="mt-1 w-full px-3 py-2 border border-slate-300 rounded-lg text-sm focus:ring-2 focus:ring-violet-500 outline-none"
            >
              {DOMAIN_OPTIONS.map((d) => (
                <option key={d} value={d}>{d}</option>
              ))}
            </select>
          </label>

          <label className="block">
            <span className="text-sm font-medium text-slate-700">Industry</span>
            <select
              value={meta.industry}
              onChange={(e) => updateMeta({ industry: e.target.value })}
              className="mt-1 w-full px-3 py-2 border border-slate-300 rounded-lg text-sm focus:ring-2 focus:ring-violet-500 outline-none"
            >
              {INDUSTRY_OPTIONS.map((i) => (
                <option key={i} value={i}>{i}</option>
              ))}
            </select>
          </label>

          <label className="block">
            <span className="text-sm font-medium text-slate-700">Estimated Duration</span>
            <select
              value={meta.duration}
              onChange={(e) => updateMeta({ duration: e.target.value })}
              className="mt-1 w-full px-3 py-2 border border-slate-300 rounded-lg text-sm focus:ring-2 focus:ring-violet-500 outline-none"
            >
              {DURATION_OPTIONS.map((d) => (
                <option key={d} value={d}>{d}</option>
              ))}
            </select>
          </label>
        </div>

        <div>
          <span className="text-sm font-medium text-slate-700">Difficulty Level</span>
          <div className="mt-2 flex gap-2">
            {DIFFICULTIES.map((d) => (
              <button
                key={d}
                type="button"
                onClick={() => updateMeta({ difficulty: d })}
                className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                  meta.difficulty === d
                    ? 'bg-violet-600 text-white'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                {d}
              </button>
            ))}
          </div>
        </div>

        <div>
          <span className="text-sm font-medium text-slate-700">Learning Objectives</span>
          <div className="mt-2 grid grid-cols-1 sm:grid-cols-2 gap-2">
            {LEARNING_OBJECTIVES.map((obj) => (
              <label
                key={obj}
                className="flex items-center gap-2 px-3 py-2 rounded-lg border border-slate-200 hover:bg-slate-50 cursor-pointer"
              >
                <input
                  type="checkbox"
                  checked={meta.learningObjectives.includes(obj)}
                  onChange={() => toggleObjective(obj)}
                  className="rounded text-violet-600 focus:ring-violet-500"
                />
                <span className="text-sm text-slate-700">{obj}</span>
              </label>
            ))}
          </div>
        </div>

        <div>
          <span className="text-sm font-medium text-slate-700">Content creation</span>
          <p className="text-xs text-slate-500 mt-1">
            Use AI, upload a source document, or build everything manually in Step 3.
          </p>
          <div className="mt-2 flex flex-wrap gap-2">
            {(['ai', 'document', 'manual'] as ContentCreationMode[]).map((mode) => (
              <button
                key={mode}
                type="button"
                onClick={() => updateMeta({ contentMode: mode })}
                className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                  (meta.contentMode ?? 'ai') === mode
                    ? 'bg-violet-600 text-white'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                {mode === 'ai' ? '✨ AI generated' : mode === 'document' ? '📄 From document' : '✏️ Manual'}
              </button>
            ))}
          </div>
          {(meta.contentMode ?? 'ai') === 'document' && (
            <div className="mt-4 p-4 rounded-xl border border-dashed border-violet-300 bg-violet-50/50">
              <p className="text-sm text-slate-700 mb-2">
                Upload a case study or syllabus (.docx, .pdf, .txt). AI will extract phases, events,
                tables, charts, and decision questions from your document.
              </p>
              <input
                ref={fileInputRef}
                type="file"
                accept=".docx,.pdf,.txt,.md,application/pdf,application/vnd.openxmlformats-officedocument.wordprocessingml.document,text/plain"
                className="hidden"
                onChange={(e) => setDocumentFile(e.target.files?.[0] ?? null)}
              />
              <div className="flex flex-wrap items-center gap-3">
                <button
                  type="button"
                  onClick={() => fileInputRef.current?.click()}
                  className="px-4 py-2 rounded-lg bg-white border border-violet-200 text-sm font-medium text-violet-700 hover:bg-violet-50"
                >
                  Choose file
                </button>
                {documentFile && (
                  <span className="text-sm text-slate-600 truncate max-w-xs">
                    {documentFile.name} ({(documentFile.size / 1024).toFixed(0)} KB)
                  </span>
                )}
              </div>
            </div>
          )}
        </div>

        <div>
          <span className="text-sm font-medium text-slate-700">Play mode</span>
          <p className="text-xs text-slate-500 mt-1">
            Single player for solo learners; multiplayer uses room codes so teams can join together.
          </p>
          <div className="mt-2 flex flex-wrap gap-2">
            {(['single', 'multiplayer'] as PlayMode[]).map((mode) => (
              <button
                key={mode}
                type="button"
                onClick={() => updateMeta({ playMode: mode })}
                className={`px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
                  (meta.playMode ?? 'single') === mode
                    ? 'bg-blue-600 text-white'
                    : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                }`}
              >
                {mode === 'single' ? '👤 Single player' : '👥 Multiplayer'}
              </button>
            ))}
          </div>
          {(meta.playMode ?? 'single') === 'multiplayer' && (
            <label className="block mt-3 max-w-xs">
              <span className="text-xs font-medium text-slate-600">Max players per room</span>
              <input
                type="number"
                min={2}
                max={12}
                value={meta.maxPlayers ?? 4}
                onChange={(e) =>
                  updateMeta({ maxPlayers: Math.min(12, Math.max(2, parseInt(e.target.value, 10) || 4)) })
                }
                className="mt-1 w-full px-3 py-2 border border-slate-300 rounded-lg text-sm focus:ring-2 focus:ring-blue-500 outline-none"
              />
            </label>
          )}
        </div>

        {generationError && (
          <div className="text-sm text-red-700 bg-red-50 border border-red-200 rounded-lg px-4 py-3">
            <strong>Import failed:</strong> {generationError}
            <p className="text-xs mt-1 text-red-600">
              Ensure GROQ_API_KEY is set in .env, server is running (port 3001), and file is .docx, .pdf, or .txt.
            </p>
          </div>
        )}

        <div className="flex flex-col sm:flex-row gap-3">
          {(meta.contentMode ?? 'ai') === 'ai' ? (
            <button
              type="button"
              onClick={runAIGeneration}
              disabled={generating}
              className="flex-1 px-6 py-3 bg-gradient-to-r from-violet-600 to-blue-600 text-white font-semibold rounded-xl hover:from-violet-700 hover:to-blue-700 transition-all shadow-md hover:shadow-lg flex items-center justify-center gap-2 disabled:opacity-60 disabled:cursor-not-allowed"
            >
              <span>{generating ? '⏳' : '✨'}</span>{' '}
              {generating ? 'Generating…' : 'Generate with AI'}
            </button>
          ) : (meta.contentMode ?? 'ai') === 'document' ? (
            <button
              type="button"
              onClick={() => documentFile && runDocumentGeneration(documentFile)}
              disabled={generating || !documentFile}
              className="flex-1 px-6 py-3 bg-gradient-to-r from-indigo-600 to-violet-600 text-white font-semibold rounded-xl hover:from-indigo-700 hover:to-violet-700 transition-all shadow-md hover:shadow-lg flex items-center justify-center gap-2 disabled:opacity-60 disabled:cursor-not-allowed"
            >
              <span>{generating ? '⏳' : '📄'}</span>{' '}
              {generating ? 'Importing document…' : 'Create from document'}
            </button>
          ) : (
            <button
              type="button"
              onClick={runManualSetup}
              disabled={generating}
              className="flex-1 px-6 py-3 bg-gradient-to-r from-teal-600 to-emerald-600 text-white font-semibold rounded-xl hover:from-teal-700 hover:to-emerald-700 transition-all shadow-md hover:shadow-lg flex items-center justify-center gap-2 disabled:opacity-60 disabled:cursor-not-allowed"
            >
              ✏️ Build manually →
            </button>
          )}
        </div>
      </div>
    </div>
  )
}
